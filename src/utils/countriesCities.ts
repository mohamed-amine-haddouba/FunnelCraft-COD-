/**
 * Dictionary of Country Key -> Alphabetically sorted list of cities
 */
export const COUNTRIES_CITIES: Record<string, string[]> = COUNTRY_LIST.reduce(
  (acc, item) => {
    acc[item.key] = [...item.cities].sort((a, b) => a.localeCompare(b));
    return acc;
  },
  {} as Record<string, string[]>
);

/**
 * Returns all countries sorted alphabetically by their canonical English key
 */
export function getCountriesSorted(): CountryEntry[] {
  return [...COUNTRY_LIST].sort((a, b) => a.key.localeCompare(b.key));
}

/**
 * Resolves canonical country key from any identifier (key, code, localized name, or partial match)
 */
export function resolveCanonicalCountryKey(countryIdentifier: string | undefined | null): string {
  if (!countryIdentifier) return '';
  const clean = countryIdentifier.trim().toLowerCase();
  if (!clean) return '';

  const exactMatch = COUNTRY_LIST.find(
    (c) =>
      c.key.toLowerCase() === clean ||
      c.code.toLowerCase() === clean ||
      c.nameAr.toLowerCase() === clean ||
      c.nameEn.toLowerCase() === clean ||
      c.nameFr.toLowerCase() === clean
  );
  if (exactMatch) return exactMatch.key;

  const partialMatch = COUNTRY_LIST.find(
    (c) =>
      c.nameAr.toLowerCase().includes(clean) ||
      c.nameEn.toLowerCase().includes(clean) ||
      c.nameFr.toLowerCase().includes(clean) ||
      c.key.toLowerCase().includes(clean)
  );
  return partialMatch ? partialMatch.key : '';
}

/**
 * Returns alphabetically sorted cities for a given country key, ISO code, or localized name
 */
export function getCitiesForCountry(countryIdentifier: string | undefined | null): string[] {
  const canonicalKey = resolveCanonicalCountryKey(countryIdentifier);
  if (!canonicalKey) return [];
  const cities = COUNTRIES_CITIES[canonicalKey];
  return Array.isArray(cities) ? [...cities].sort((a, b) => a.localeCompare(b)) : [];
}

